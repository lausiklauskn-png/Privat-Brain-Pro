import {readFile,writeFile,copyFile,mkdir,rm,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {resolve,join} from 'node:path';
const windows=resolve(import.meta.dirname,'..'),root=resolve(windows,'..');
const config=JSON.parse(await readFile(join(windows,'src-tauri/tauri.conf.json'),'utf8'));
if(!/^\d+\.\d+\.\d+-preview\.\d+$/.test(config.version))throw Error('Review distribution version.');
const source=process.env.PB_SOURCE_COMMIT||execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
if(!/^[a-f0-9]{40}$/.test(source))throw Error('Missing exact source commit.');
const input=join(windows,'src-tauri/target/release/bundle/nsis'),out=join(windows,'distribution');
const installers=(await readdir(input)).filter(name=>name.endsWith('-setup.exe'));
if(installers.length!==1)throw Error('Expected exactly one accepted production installer.');
await rm(out,{recursive:true,force:true});await mkdir(out,{recursive:true});
const name=`Private-Brain-Pro-Windows-${config.version}-x64-setup.exe`;
await copyFile(join(input,installers[0]),join(out,name));
const bytes=await readFile(join(out,name)),sha256=createHash('sha256').update(bytes).digest('hex');
await copyFile(join(windows,'engine/build/shared-source.json'),join(out,'shared-source.json'));
await writeFile(join(out,'windows-build.json'),JSON.stringify({version:config.version,sourceCommit:source,buildCommit:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),architecture:'x64',signing:'unsigned',testEndpoint:false,installer:name,sha256,size:bytes.length,acceptanceRun:process.env.GITHUB_RUN_ID||null},null,2)+'\n');
let sums='';for(const file of [name,'shared-source.json','windows-build.json'])sums+=createHash('sha256').update(await readFile(join(out,file))).digest('hex')+'  '+file+'\n';
await writeFile(join(out,'SHA256SUMS'),sums);
console.log(JSON.stringify({name,sha256,size:bytes.length,source}));
